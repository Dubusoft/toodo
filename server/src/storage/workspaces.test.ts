import { expect, test } from "bun:test";
import { commit, expectFailure, memoryStorage, newTask, seedCommits, stored, workspace } from "./storage-fixtures.ts";

test("Workspaces update, archive, restore, and purge with their tasks", () => {
  const storage = memoryStorage();
  const ws = workspace(storage);
  const kept = workspace(storage, "Kept");
  const a = storage.createTask(newTask(ws, "A"));
  const b = storage.createTask(newTask(ws, "B"));
  const keptTask = storage.createTask(newTask(kept, "Kept"));
  storage.addDependency(b.id, a.id);
  const record = commit(a.id, "aaa", 1);
  seedCommits(storage, [record]);
  const renamed = { ...ws, name: "Renamed", description: "Workspace notes", repository: "discord:work" };
  storage.updateWorkspace(renamed);
  expect(storage.getWorkspace(ws.id)).toEqual(renamed);
  expectFailure(() => storage.purgeWorkspace(ws.id), { kind: "workspace_not_archived", workspace: ws.id });
  storage.archiveWorkspace(ws.id);
  expect(storage.getWorkspace(ws.id)).toBeNull();
  expect(storage.listWorkspaces()).toEqual([kept]);
  expect(storage.archivedWorkspaces()).toEqual([{ ...renamed, archivedAt: 100 }]);
  expect(storage.getTask(a.id)).toBeNull();
  expect(storage.listAllTasks()).toEqual([keptTask]);
  expect(storage.archivedTasks()).toEqual([]);
  expect(storage.reviewTasks().map(({ id }) => id)).toEqual([a.id, b.id, keptTask.id]);
  expect(storage.reviewTasks()[1].dependsOn).toEqual(new Set([a.id]));
  expect(storage.listCommitRecords(a.id)).toEqual([record]);
  expectFailure(() => storage.restoreTask(a.id), { kind: "workspace_archived", workspace: ws.id, task: a.id });
  const missing = { kind: "workspace_not_found", workspace: ws.id } as const;
  expectFailure(() => storage.archiveWorkspace(ws.id), missing);
  expectFailure(() => storage.updateWorkspace(renamed), missing);
  expectFailure(() => storage.createTask(newTask(ws, "Orphan")), missing);
  expect(storage.restoreWorkspace(ws.id)).toEqual(renamed);
  expect(stored(storage, b.id).dependsOn).toEqual(new Set([a.id]));
  storage.archiveWorkspace(ws.id);
  storage.purgeWorkspace(ws.id);
  expect(storage.reviewTasks()).toEqual([keptTask]);
  expect(storage.db.query("SELECT task_id FROM task_dependencies").all()).toEqual([]);
  expect(storage.listCommitRecords(a.id)).toEqual([]);
  expect(storage.listTasks(kept.id)).toEqual([keptTask]);
  expectFailure(() => storage.purgeWorkspace(ws.id), missing);
});
